  </p>
  <h2>いつ利用されているかを確認</h2>
  <p>
    利用件数を日別・時間帯別に見ることで、窓口の開いていない時間にも質問が寄せられているか、特定の日に問い合わせが増えていないかを確認できます。集計期間を指定し、周知やホームページの更新前後を比較する際にも利用します。
  </p>
  <h2>評価と回答できなかった質問を確認</h2>
  <p>
    利用者から寄せられた回答への評価に加え、回答できなかった質問や、回答の根拠を十分に得られなかった質問を確認するための項目を設けています。件数だけで判断せず、実際の質問と参照情報を見て原因を探ることを想定しています。
  </p>
  <ul>
    <li>公式ページに必要な説明があるかを確認する</li>
    <li>AIが参照する資料の範囲や案内方針を見直す</li>
    <li>よくある質問やホームページの説明を補う</li>
  </ul>
  <p>
    利用者の評価やシステムの判定は、回答の正しさを保証するものではありません。改善対象を見つける手掛かりとして扱い、個別の回答内容も確認します。
  </p>
