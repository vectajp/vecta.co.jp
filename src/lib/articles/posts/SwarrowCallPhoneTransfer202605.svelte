<div class="article-body">
  <p>
    2026年5月22日から30日にかけて、SwarrowCallでAIが一次受付を行った後に、担当先へ電話を取り次ぐ機能を実装・検証しました。取次先の選択、電話の転送、問い合わせ内容の引継ぎを扱う開発です。
  </p>
  <h2>問い合わせ内容と設定に沿って取次先を選ぶ</h2>
  <p>
    AIがすべての問い合わせを回答だけで完結させるのではなく、人による確認が必要な場面で担当先につなぐことを想定しています。取次先は、登録された連絡先や電話受付の流れに従って選びます。
  </p>
  <p>
    外線への転送に加え、SIPを利用する内線への取次ぎも開発の対象にしています。実際に使用できる経路は、電話設備と接続方法によって異なります。
  </p>
  <h2>受付した内容を担当先へ引き継ぐ</h2>
  <p>
    転送先に問い合わせの要点を伝えてから通話をつなぐ方式も扱っています。担当者が用件を把握して応対を始められるよう、AIが受け付けた内容を引継ぎ用に整理します。
  </p>
  <p>
    同じ通話で転送が重複して始まることを防ぐ処理や、別の担当先へ再度取り次ぐ際の処理も見直しました。取次先が応答できない場合の案内は、受付時間や折り返しの運用に合わせて決める必要があります。
  </p>
  <h2>電話設備と運用条件に合わせて検証</h2>
  <p>
    本記事は5月に実装・検証した内容を紹介する開発レポートです。利用する際は、転送先の電話設備、受付時間、引継ぎ方法などの条件を確認し、接続試験と運用の調整を行います。
  </p>
