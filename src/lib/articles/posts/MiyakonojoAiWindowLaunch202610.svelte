<div class="article-body">
  <p>
    2026年10月1日、都城市公式ホームページで、SwarrowChatを活用したAI相談窓口の運用が始まりました。市の手続きや暮らしに関する質問を、テキストチャットや音声で受け付けます。
  </p>
  <h2>公式情報をもとに手続きや必要書類を案内</h2>
  <p>
    AI相談窓口は、市公式ホームページや電子申請ページなどの情報から、質問に関係する内容を探して回答します。回答とあわせて参照元を表示し、詳しい説明や手続きのページを確認できる構成です。
  </p>
  <p>
    相談は24時間受け付け、多言語での案内にも対応します。音声で質問する方法も用意し、文字の入力が難しい場面でも利用できるようにしています。申請や届出そのものの受付方法は手続きによって異なるため、案内先の公式ページで確認します。
  </p>
