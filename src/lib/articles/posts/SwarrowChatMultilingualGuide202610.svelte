  <p>
    2026年7月20日、SwarrowChatで質問の言語に合わせて回答する設定を実装し、検証環境へ反映しました。自治体の公式情報をもとに、多言語で問い合わせに答えるための開発です。
  </p>
  <h2>質問に使われた言語に合わせて案内</h2>
  <p>
    質問の言語を自動で判定する設定では、利用者が入力した言語に合わせて回答します。日本語の制度名や手続き名をあらかじめ知らなくても、知りたい内容を自分の言葉で尋ねられることを目指しています。
  </p>
  <p>
    検証環境では、日本語で尋ねた質問に日本語で、英語で尋ねた質問に英語で回答する動作を確認しました。固定した言語で答える設定と、自動で判定する設定を、窓口の案内方針に合わせて選べる構成です。
  </p>
  <h2>回答から公式の説明を確認</h2>
  <p>
    案内のもとになるのは、自治体が公開しているホームページや資料です。回答とあわせて参照元を確認できるため、制度の名称や詳しい条件は元の情報に戻って確かめられます。
  </p>
  <p>
    翻訳された回答だけで手続きが完結するわけではありません。申請書の表記、提出方法、本人確認などは、案内先の公式ページや担当窓口で確認します。利用する言語や質問内容によって表現の確認が必要な場合もあります。
  </p>
