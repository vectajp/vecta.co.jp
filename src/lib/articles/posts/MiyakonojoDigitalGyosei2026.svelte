  <h2>実証を通じた案内内容の改善</h2>
  <p>
    都城市では、利用件数や回答への評価、問い合わせの傾向を確認しながら、AI窓口の有効性を検証する方針が示されています。回答できなかった質問も、ホームページに不足している情報や分かりにくい表現を見直す手掛かりとして活用する考えが紹介されています。
  </p>
  <p>
