<div class="article-body">
  <p>
    2026年4月24日、SwarrowChatでホームページを定期的に取得する機能と、取得スケジュールを管理する画面を実装しました。新しく公開されたページを、AIが回答時に参照する情報へ追加するための開発です。
  </p>
  <h2>ホームページを定期的に取得</h2>
  <p>
    対象のホームページと取得範囲を登録し、毎日・毎週・毎月の間隔で定期取得するスケジュールを設定します。管理画面では、次の実行日時や前回の実行状況を確認できるようにしています。
  </p>
  <p>
    今回の実装では、新しく見つかったページを取り込み、登録済みのURLは重複して追加しない構成です。既存のページ本文が変更された場合の再取得とは分けて扱います。
  </p>
  <h2>回答の参照元を確認できる構成</h2>
  <p>
    AIは、取り込んだ情報の中から質問に関係する内容を探して案内します。回答と参照元のページをあわせて示し、利用者が詳しい条件や手続きの案内を確認できるようにしています。
  </p>
  <h2>更新間隔と取得範囲を運用で確認</h2>
  <p>
    新しい情報を取り込む時期は、取得の間隔や対象ページの範囲によって変わります。運用では取得の実行状況を確認し、重要な制度変更については、既存資料の更新もあわせて確認します。本記事は4月24日の定期取得機能の開発内容を紹介しています。
  </p>
</div>
