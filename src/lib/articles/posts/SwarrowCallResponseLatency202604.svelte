  <p>
    2026年4月30日、SwarrowCallで情報検索の準備と実行のタイミングを見直し、開発環境へ反映しました。通話開始時の準備と発話中の先行検索により、質問してから回答が始まるまでの待ち時間を減らすための開発です。
  </p>
  <h2>会話の開始時に検索の準備を進める</h2>
  <p>
    問い合わせ内容に関係する資料を検索して答える電話では、回答の生成だけでなく、検索の準備にも時間がかかります。通話の開始に合わせて準備を進め、質問を受けた後に処理が集中しないようにしています。
  </p>
  <h2>発話の途中から関係する情報を探す</h2>
  <p>
    音声認識の途中経過から質問の内容を判断できる場合は、発話が終わる前に検索を始めます。最終的に確定した発話と内容が合うときに、その検索結果を利用する構成です。
  </p>
  <p>
    話の途中で内容が変わった場合は、先に行った検索結果をそのまま使いません。待ち時間を減らす処理と、確定した質問に沿って答える処理をあわせて扱います。
  </p>
  <h2>実際の通話で確認する項目</h2>
  <p>
    待ち時間は、音声認識、検索対象、回答の長さ、通信の状態などによって変わります。質問が正しく伝わったか、回答が途中で重ならないかといった会話全体の動作も確認します。
  </p>
