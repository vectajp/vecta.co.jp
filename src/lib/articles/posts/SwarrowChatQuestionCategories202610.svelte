<div class="article-body">
  <p>
    2026年10月1日、SwarrowChatに寄せられた質問を分類し、問い合わせの傾向を確認する機能を実装しました。分類項目の設定、新しく届いた質問の自動分類、カテゴリ別の集計の開発を紹介します。
  </p>
  <h2>案内する業務に合わせて分類項目を設定</h2>
  <p>
    子育て、ごみ、住まいなど、運用先の業務に合わせて分類項目を設定します。項目ごとに名前や説明、判断の手掛かりとなるキーワード、関連する担当部署を登録できるようにしています。
  </p>
  <p>
    分類項目を固定せず、運用の中で整理し直せる構成です。自治体全体を案内する窓口と、特定の制度だけを扱う窓口で、必要な分類の細かさが異なることを想定しています。
  </p>
  <h2>新しい質問を分類して傾向を確認</h2>
  <p>
    自動分類を有効にした窓口では、新しく届いた質問を設定した項目に沿って分類します。管理画面ではカテゴリごとの件数を確認し、問い合わせが多い分野や、説明を見直したいテーマを探せます。
  </p>
  <p>
    未分類の質問や判定が定まらない質問も区別して扱います。分類結果をそのまま確定的な事実とせず、質問内容を確認しながら設定を見直すことが大切です。
  </p>
  <h2>件数と回答内容をあわせて確認</h2>
  <p>
    利用状況や回答評価のレポートと組み合わせ、問い合わせの量と案内内容の両方を確認するための開発です。10月の実装内容を紹介しており、導入先ごとの有効化や提供範囲は運用設定によって異なります。
  </p>
