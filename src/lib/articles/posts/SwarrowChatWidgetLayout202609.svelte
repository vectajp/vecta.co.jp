  <p>
    2026年9月18日、SwarrowChatのチャット画面の移動、サイズ変更、スマートフォンでの表示を見直しました。自治体ホームページを読みながら質問できるようにするための開発です。
  </p>
  <h2>ページの内容に合わせて移動とサイズ変更</h2>
  <p>
    PCでは、チャット画面をドラッグして位置を変え、辺や角から大きさを調整できるようにしています。公式ページの説明とAIの回答を見比べるときに、読んでいる箇所が隠れにくくするための変更です。
  </p>
  <p>
    サイズ変更は上下左右と四隅の8方向を扱い、表示領域の中で位置と大きさを調整します。管理画面で設定した配置と、公開画面のプレビューの見え方も揃えるようにしています。
  </p>
  <h2>スマートフォンでは画面幅に合わせて表示</h2>
  <p>
    画面の狭い端末では、PCと同じ大きさの小窓をそのまま置くと、回答も元のページも読みづらくなります。端末の表示領域に合わせたレイアウトを設け、起動ボタンやチャット画面の位置を確認しました。
  </p>
  <h2>複数の表示条件を検証</h2>
  <p>
    9月の開発では、起動ボタン、画面の移動とリサイズ、モバイル表示を対象にレイアウトを検証しています。本記事は開発内容の紹介です。導入先での表示方法は、ホームページへの設置設定や利用する画面の版によって異なります。
  </p>
